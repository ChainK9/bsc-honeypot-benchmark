// Generates script/DeployTestnet.s.sol from manifest.json (public tokens, manifest order).
// Run: node scripts/gen-deploy-testnet.mjs   (test/score.test.mjs checks the file is up to date)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);

export function render(manifest) {
  const pub = manifest.filter((t) => t.release === "public");
  const label = (t, n) => {
    const kind = t.class === "clean" ? "Control" : t.class === "info" ? "Info" : "Trap";
    const text = `ChainK9 ${kind} #${n}` + (t.class === "clean" ? "" : `: ${t.mechanism}`);
    if (/["\\]/.test(text)) throw new Error(`${t.id}: label has a quote or backslash`);
    return text;
  };
  const imports = pub.map((t) => `import {${t.id}} from "../src/${t.id}.sol";`).join("\n");
  const calls = pub
    .map((t, i) => `        _add(${i + 1}, "${t.id}", "${label(t, i + 1)}", address(new ${t.id}()));`)
    .join("\n");
  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

// GENERATED by scripts/gen-deploy-testnet.mjs from manifest.json. Do not edit by hand.
// TEST FIXTURE deployment: BSC testnet (chain id 97) only, with test BNB.
//
//   forge script script/DeployTestnet.s.sol --rpc-url $BSC_TESTNET_RPC --account <keystore> --broadcast
//
// Token names stay as written in each contract. This script records the public label and the
// CK9T<n> symbol for each token in deployments/bsc-testnet.json.
${imports}

interface Vm {
    enum ForgeContext { TestGroup, Test, Coverage, Snapshot, ScriptGroup, ScriptDryRun, ScriptBroadcast, ScriptResume, Unknown }

    function startBroadcast() external;
    function stopBroadcast() external;
    function isContext(ForgeContext) external view returns (bool);
    function writeFile(string calldata, string calldata) external;
    function toString(address) external pure returns (string memory);
    function toString(uint256) external pure returns (string memory);
}

interface IToken {
    function balanceOf(address) external view returns (uint256);
    function approve(address, uint256) external returns (bool);
    function pair() external view returns (address);
}

interface IRouter {
    function addLiquidityETH(address, uint256, uint256, uint256, address, uint256) external payable;
}

contract DeployTestnet {
    Vm private constant vm = Vm(address(uint160(uint256(keccak256("hevm cheat code")))));
    // PancakeSwap V2 router on BSC testnet.
    address private constant ROUTER = 0xD99D1c33F9fC3444f8101754aBC46c52416550D1;
    uint256 private constant LIQUIDITY = 0.005 ether;

    string private json;

    function run() external {
        require(block.chainid == 97, "BSC testnet only");
        vm.startBroadcast();
${calls}
        vm.stopBroadcast();
        // Only a real broadcast writes the file; a dry run leaves it alone.
        if (vm.isContext(Vm.ForgeContext.ScriptBroadcast)) {
            vm.writeFile("deployments/bsc-testnet.json", string.concat("[", json, "\\n]\\n"));
        }
    }

    /// Adds 0.005 test BNB against half the deployer's supply and records the token.
    function _add(uint256 n, string memory id, string memory label, address token) private {
        uint256 half = IToken(token).balanceOf(tx.origin) / 2;
        IToken(token).approve(ROUTER, half);
        IRouter(ROUTER).addLiquidityETH{value: LIQUIDITY}(token, half, 0, 0, tx.origin, 4102444800);
        json = string.concat(
            json, n == 1 ? "\\n" : ",\\n",
            '  {"n": ', vm.toString(n), ', "id": "', id, '", "label": "', label,
            '", "symbol": "CK9T', vm.toString(n), '", "token": "', vm.toString(token),
            '", "pair": "', vm.toString(IToken(token).pair()), '"}'
        );
    }
}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(new URL("script/DeployTestnet.s.sol", root), render(JSON.parse(readFileSync(new URL("manifest.json", root), "utf8"))));
}
